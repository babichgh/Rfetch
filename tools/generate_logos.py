#!/usr/bin/env python3
"""Generate `src/logo/generated.rs` from vendored fastfetch logo art.

The art under `logos/` is taken verbatim from fastfetch's `src/logo/ascii/`
(MIT, see LICENSE-fastfetch). This script only reads the metadata that lives in
fastfetch's C headers — the per-logo display names and colour palettes — and
emits a Rust table. It never modifies the art itself.

Usage:
    python3 tools/generate_logos.py [--check] [--fastfetch PATH]

    --check      regenerate into memory and fail if the committed file differs
    --fastfetch  path to a fastfetch checkout, to read the .inc metadata from
                 (defaults to /tmp/opencode/ffprobe)

fastfetch declares each logo as:

    #ifdef FASTFETCH_DATATEXT_LOGO_FEDORA
    {
        .names = { "Fedora" },
        .lines = FASTFETCH_DATATEXT_LOGO_FEDORA,
        .colors = { FF_COLOR_FG_BLUE, FF_COLOR_FG_WHITE },
    },
    #endif

`$1`, `$2`, ... inside a .txt file are indices into `.colors`, so both halves
have to be kept together or the art renders wrong.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOGOS_DIR = ROOT / "logos"
OUT = ROOT / "src" / "logo" / "generated.rs"

# The 16 named foreground colours fastfetch uses, as truecolor RGB.
NAMED = {
    "FF_COLOR_FG_BLACK": (0, 0, 0),
    "FF_COLOR_FG_RED": (255, 0, 0),
    "FF_COLOR_FG_GREEN": (0, 255, 0),
    "FF_COLOR_FG_YELLOW": (255, 255, 0),
    "FF_COLOR_FG_BLUE": (0, 0, 255),
    "FF_COLOR_FG_MAGENTA": (255, 0, 255),
    "FF_COLOR_FG_CYAN": (0, 255, 255),
    "FF_COLOR_FG_WHITE": (255, 255, 255),
    "FF_COLOR_FG_LIGHT_BLACK": (128, 128, 128),
    "FF_COLOR_FG_LIGHT_RED": (255, 85, 85),
    "FF_COLOR_FG_LIGHT_GREEN": (85, 255, 85),
    "FF_COLOR_FG_LIGHT_YELLOW": (255, 255, 85),
    "FF_COLOR_FG_LIGHT_BLUE": (85, 85, 255),
    "FF_COLOR_FG_LIGHT_MAGENTA": (255, 85, 255),
    "FF_COLOR_FG_LIGHT_CYAN": (85, 255, 255),
    "FF_COLOR_FG_LIGHT_WHITE": (255, 255, 255),
}

# Used when a logo declares no palette at all: a plain white fallback.
FALLBACK = (204, 204, 204)

CUBE = (0, 95, 135, 175, 215, 255)


def xterm256(n: int) -> tuple[int, int, int]:
    """Convert an xterm-256 palette index to RGB."""
    if n < 16:
        base = [
            (0, 0, 0), (205, 0, 0), (0, 205, 0), (205, 205, 0),
            (0, 0, 238), (205, 0, 205), (0, 205, 205), (229, 229, 229),
            (127, 127, 127), (255, 0, 0), (0, 255, 0), (255, 255, 0),
            (92, 92, 255), (255, 0, 255), (0, 255, 255), (255, 255, 255),
        ]
        return base[n]
    if n < 232:
        n -= 16
        return (CUBE[n // 36], CUBE[(n // 6) % 6], CUBE[n % 6])
    g = 8 + 10 * (n - 232)
    return (g, g, g)


def parse_colors(body: str) -> list[tuple[int, int, int]]:
    """Pull the `.colors = { ... }` list out of one logo entry."""
    m = re.search(r"\.colors\s*=\s*\{(.*?)\}", body, re.S)
    if not m:
        return []
    out: list[tuple[int, int, int]] = []
    # Order matters: the 256 form has a quoted argument the plain one lacks.
    for tok in re.finditer(
        r'FF_COLOR_FG_256\s*"(\d+)"'
        r'|FF_COLOR_FG_([A-Z0-9_]+)'
        r'|FF_COLOR_FG_([A-Z0-9_]*)\s*"([0-9a-fA-F]+)"',
        m.group(1),
    ):
        if tok.group(1) is not None:
            out.append(xterm256(int(tok.group(1))))
        elif tok.group(2):
            name = f"FF_COLOR_FG_{tok.group(2)}"
            out.append(NAMED.get(name, FALLBACK))
        elif tok.group(3) == "RGB":
            h = tok.group(4)
            out.append((int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)))
    return out


def parse_fastfetch(src: pathlib.Path) -> dict[str, tuple[list[str], list]]:
    """Map art stem -> (display names, palette) from the .inc headers."""
    meta: dict[str, tuple[list[str], list]] = {}
    for inc in sorted(src.glob("*.inc")):
        text = inc.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(
            r"#ifdef\s+(FASTFETCH_DATATEXT_LOGO_([A-Z0-9_]+))(.*?)#endif",
            text,
            re.S,
        ):
            body = m.group(3)
            nm = re.search(r'\.names\s*=\s*\{(.*?)\}', body, re.S)
            names = re.findall(r'"([^"]+)"', nm.group(1)) if nm else []
            meta[m.group(2).lower()] = (names, parse_colors(body))
    return meta


def escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


HEADER = """\
// @generated by tools/generate_logos.py -- do not edit by hand.
//
// Logo art under `logos/` comes verbatim from fastfetch's `src/logo/ascii/`,
// MIT licensed; see LICENSE-fastfetch. Only the per-logo name and colour
// metadata was transformed into Rust.
//
// `$1`, `$2`, ... in a .txt file index into that logo's `colors` list.

pub struct RawLogo {
    /// Lowercase names to match against: primary logo name plus aliases.
    pub names: &'static [&'static str],
    /// Palette indexed by `$N` in `art`.
    pub colors: &'static [(u8, u8, u8)],
    /// Raw art, still containing `$N` markers.
    pub art: &'static str,
}

pub static LOGOS: &[RawLogo] = &[
"""

FOOTER = "];\n"


def rustfmt(source: str) -> str:
    """Format through rustfmt so `--check` agrees with `cargo fmt`.

    Without this the generator and `cargo fmt` fight over the output and
    `--check` reports a stale file immediately after a fresh generation.
    """
    if shutil.which("rustfmt") is None:
        return source
    try:
        done = subprocess.run(
            ["rustfmt", "--edition", "2024", "--emit", "stdout"],
            input=source,
            capture_output=True,
            text=True,
            check=True,
        )
        return done.stdout
    except (subprocess.CalledProcessError, OSError):
        return source


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--fastfetch", default="/tmp/opencode/ffprobe")
    args = ap.parse_args()

    src = pathlib.Path(args.fastfetch) / "src" / "logo" / "ascii"
    meta = parse_fastfetch(src) if src.is_dir() else {}

    arts = sorted(LOGOS_DIR.glob("*/*.txt"))
    if not arts:
        print("no art found under logos/", file=sys.stderr)
        return 1

    chunks = [HEADER]
    missing = []

    entries = []
    for path in arts:
        stem = path.stem
        names, colors = meta.get(stem, ([], []))
        if not names:
            missing.append(stem)
        if not colors:
            colors = [FALLBACK]
        entries.append((path, stem, names, colors))

    # The file stem is unique by construction, so it is the primary lookup
    # key. fastfetch aliases overlap across logos -- nixos_old_small claims
    # "nixos2", which is also a real logo file -- and the file that actually
    # is called nixos2 should win that name.
    stems = {stem for _, stem, _, _ in entries}

    for path, stem, names, colors in entries:
        lookup = [stem]
        for n in names:
            k = n.strip().lower()
            if k and k not in lookup and k not in stems:
                lookup.append(k)
        art = os.path.relpath(path, OUT.parent).replace(os.sep, "/")
        chunks.append(
            "    RawLogo {\n"
            f"        names: &[{', '.join(f'\"{escape(n)}\"' for n in lookup)}],\n"
            f"        colors: &[{', '.join(f'({r}, {g}, {b})' for r, g, b in colors)}],\n"
            f"        art: include_str!(\"{art}\"),\n"
            "    },\n"
        )

    chunks.append(FOOTER)
    out = rustfmt("".join(chunks))

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != out:
            print("generated.rs is out of date; rerun the generator", file=sys.stderr)
            return 1
        print(f"generated.rs is up to date ({len(arts)} logos)")
        return 0

    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(arts)} logos")
    if missing:
        print(f"  {len(missing)} with no .inc metadata, fell back to filename:")
        for m in missing:
            print(f"    {m}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())